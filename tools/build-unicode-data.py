#!/usr/bin/env python3
"""Generates data/unicode-names.js and data/unicode-blocks.js from Python's unicodedata and fontTools.
Run from the project root:  python3 tools/build-unicode-data.py   (needs: pip install fonttools)"""
import unicodedata as ud, json, os
from fontTools.unicodedata import Blocks

# --- block table (always loaded, small) ---
starts, vals = Blocks.RANGES, Blocks.VALUES
blocks = []
for i, s in enumerate(starts):
    if vals[i] == 'No_Block': continue
    e = (starts[i + 1] - 1) if i + 1 < len(starts) else 0x10FFFF
    blocks.append([s, e, vals[i]])

# --- names (lazy loaded): whole blocks that matter for nicknames ---
WANT = """Basic Latin|Latin-1 Supplement|Latin Extended-A|Latin Extended-B|IPA Extensions|Spacing Modifier Letters|Combining Diacritical Marks|Greek and Coptic|Cyrillic|Cyrillic Supplement|Armenian|Hebrew|Arabic|Devanagari|Thai|Tibetan|Georgian|Cherokee|Unified Canadian Aboriginal Syllabics|Ogham|Runic|Phonetic Extensions|Phonetic Extensions Supplement|Combining Diacritical Marks Supplement|Latin Extended Additional|Greek Extended|General Punctuation|Superscripts and Subscripts|Currency Symbols|Combining Diacritical Marks for Symbols|Letterlike Symbols|Number Forms|Arrows|Mathematical Operators|Miscellaneous Technical|Control Pictures|Enclosed Alphanumerics|Box Drawing|Block Elements|Geometric Shapes|Miscellaneous Symbols|Dingbats|Miscellaneous Mathematical Symbols-A|Supplemental Arrows-A|Braille Patterns|Supplemental Arrows-B|Miscellaneous Mathematical Symbols-B|Supplemental Mathematical Operators|Miscellaneous Symbols and Arrows|Latin Extended-C|CJK Radicals Supplement|Kangxi Radicals|CJK Symbols and Punctuation|Hiragana|Katakana|Bopomofo|Enclosed CJK Letters and Months|CJK Compatibility|Latin Extended-D|Javanese|Variation Selectors|Halfwidth and Fullwidth Forms|Specials|Mathematical Alphanumeric Symbols|Enclosed Alphanumeric Supplement|Geometric Shapes Extended|Supplemental Symbols and Pictographs""".split('|')
by = {b[2]: b for b in blocks}
runs = []; total = 0
for name in WANT:
    s, e, _ = by[name]
    lines = []
    for cp in range(s, e + 1):
        try: n = ud.name(chr(cp))
        except ValueError: n = ''
        if cp < 0x20 or 0x7F <= cp < 0xA0: n = ''
        lines.append(n)
    while lines and lines[-1] == '': lines.pop()
    if not any(lines): continue
    runs.append([s, '\n'.join(lines)]); total += sum(1 for l in lines if l)
os.makedirs('data', exist_ok=True)
with open('data/unicode-names.js', 'w', encoding='utf-8') as f:
    f.write('/* Generated by tools/build-unicode-data.py. Unicode %s names from Python unicodedata. */\n' % ud.unidata_version)
    f.write('window.PNL=window.PNL||{};PNL.UNAMES_VERSION=%s;PNL.UNAMES=%s;\nPNL.UNAMES_READY&&PNL.UNAMES_READY();\n' % (json.dumps(ud.unidata_version), json.dumps(runs, ensure_ascii=False, separators=(',', ':'))))
with open('data/unicode-blocks.js', 'w', encoding='utf-8') as f:
    f.write('/* Generated by tools/build-unicode-data.py (fontTools block table). */\nwindow.PNL=window.PNL||{};PNL.BLOCKS=%s;\n' % json.dumps(blocks, ensure_ascii=False, separators=(',', ':')))
print('blocks', len(blocks), '| named chars', total, '| runs', len(runs), '| unicode', ud.unidata_version)
